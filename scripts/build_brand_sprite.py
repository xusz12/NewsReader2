"""Extract the supplied logo paths for the compact, theme-aware app header.

Run after replacing static/brand/mark-small.svg or lockup.svg.
No font installation, path redrawing or third-party dependencies are needed.
"""
from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1] / "static" / "brand"
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG)


def build_sprite():
    sprite = ET.Element(f"{{{SVG}}}svg")
    sprite.append(ET.Comment(" Generated by scripts/build_brand_sprite.py; edit the source assets. "))
    # The consuming SVG owns the viewBox; groups avoid a second viewport transform.
    definitions = ET.SubElement(sprite, f"{{{SVG}}}defs")
    mark = ET.SubElement(definitions, f"{{{SVG}}}g", {"id": "mark-small"})
    source_mark = ET.parse(ROOT / "mark-small.svg").getroot()
    mark.append(deepcopy(source_mark.find(f"{{{SVG}}}path")))

    wordmark = ET.SubElement(definitions, f"{{{SVG}}}g", {
        "id": "wordmark", "fill": "currentColor",
    })
    source_wordmark = ET.parse(ROOT / "lockup.svg").find(f".//{{{SVG}}}g[@id='brand-wordmark']")
    for path in source_wordmark:
        wordmark.append(deepcopy(path))
    ET.indent(sprite, space="  ")
    ET.ElementTree(sprite).write(ROOT / "header-symbols.svg", encoding="utf-8", xml_declaration=True)


if __name__ == "__main__":
    build_sprite()
