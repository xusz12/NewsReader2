import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const outdir = path.join(root, "static/vendor");
await mkdir(outdir, { recursive: true });
const result = await build({
  absWorkingDir: root,
  entryPoints: ["frontend/idea-markdown-editor.js"],
  outfile: "static/vendor/idea-markdown-editor.js",
  bundle: true, format: "esm", target: ["es2022"], minify: true,
  metafile: true, legalComments: "eof",
  banner: { js: "// Generated by npm run build:idea-editor. Source: frontend/idea-markdown-editor.js" },
});
const packages = [...new Set(Object.keys(result.metafile.inputs).map(name => /^node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(name)?.[1]).filter(Boolean))].sort();
const licenses = await Promise.all(packages.map(async name => {
  const dir = path.join(root, "node_modules", name);
  const info = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
  let license;
  for (const file of ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENSE-MIT.txt"]) {
    try { license = await readFile(path.join(dir, file), "utf8"); break; } catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  if (!license) throw new Error(`Missing license for ${name}`);
  return `${name}@${info.version}\n${license}`;
}));
await writeFile(path.join(outdir, "idea-markdown-editor.LICENSE.txt"), licenses.join("\n\n---\n\n"));
await writeFile(path.join(outdir, "prosemirror.css"), await readFile(path.join(root, "node_modules/prosemirror-view/style/prosemirror.css")));
